create or replace function public.quiz_session_summary (
  selected_session_id   uuid,
  authenticated_user_id uuid
)
  returns jsonb
  language plpgsql
  security definer
  set search_path to ''
  AS $function$
declare
  selected_session public.game_sessions%rowtype;
  correct_count integer;
  incorrect_count integer;
  timed_out_count integer;
  not_played_count integer;
  questions_reached_count integer;
  answered_count integer;
  completed_question_count integer;
  accuracy_percentage numeric;
  completion_percentage numeric;
  duration_seconds integer;
begin
  select game_sessions.*
  into selected_session
  from public.game_sessions
  where game_sessions.id = selected_session_id
    and game_sessions.user_id = authenticated_user_id;

  if not found then
    raise exception 'Quiz session was not found'
      using errcode = 'P0002';
  end if;

  select
    count(*) filter (where result = 'correct'),
    count(*) filter (where result = 'incorrect'),
    count(*) filter (where status = 'timed_out'),
    count(*) filter (where status in ('abandoned', 'not_played')),
    count(*) filter (
      where status in (
        'active',
        'submitted',
        'answered',
        'timed_out',
        'abandoned'
      )
    )
  into
    correct_count,
    incorrect_count,
    timed_out_count,
    not_played_count,
    questions_reached_count
  from public.game_session_questions
  where session_id = selected_session_id;

  answered_count := correct_count + incorrect_count;
  completed_question_count := answered_count + timed_out_count;

  accuracy_percentage := case
    when answered_count = 0 then 0
    else round((correct_count::numeric / answered_count::numeric) * 100, 2)
  end;

  completion_percentage := case
    when selected_session.total_questions = 0 then 0
    else round(
      (
        completed_question_count::numeric
        / selected_session.total_questions::numeric
      ) * 100,
      2
    )
  end;

  duration_seconds := case
    when selected_session.started_at is null then 0
    else greatest(
      0,
      floor(
        extract(
          epoch from (
            coalesce(selected_session.ended_at, clock_timestamp())
            - selected_session.started_at
          )
        )
      )::integer
    )
  end;

  return jsonb_build_object(
    'sessionId', selected_session.id,
    'status', selected_session.status,
    'endReason', selected_session.end_reason,
    'areaId', selected_session.area_id,
    'areaName', selected_session.area_name,
    'gameType', selected_session.game_type,
    'difficulty', selected_session.difficulty,
    'totalQuestions', selected_session.total_questions,
    'correct', correct_count,
    'incorrect', incorrect_count,
    'timedOut', timed_out_count,
    'notPlayed', not_played_count,
    'questionsReached', questions_reached_count,
    'answered', answered_count,
    'accuracyPercentage', accuracy_percentage,
    'completionPercentage', completion_percentage,
    'durationSeconds', duration_seconds
  );
end;
$function$;

