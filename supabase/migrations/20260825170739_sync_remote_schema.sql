create or replace function public.prune_game_session_history()
  returns trigger
  language plpgsql
  security definer
  set search_path to ''
  AS $function$
begin
  perform pg_catalog.pg_advisory_xact_lock(
    20260726,
    pg_catalog.hashtext(new.user_id::text)
  );

  with ranked_sessions as materialized (
    select
      game_sessions.id,
      row_number() over (
        partition by game_sessions.user_id
        order by
          game_sessions.ended_at desc nulls last,
          game_sessions.id desc
      ) as session_rank
    from public.game_sessions
    where game_sessions.user_id = new.user_id
      and game_sessions.status in ('completed', 'exited')
  )
  delete from public.game_sessions
  using ranked_sessions
  where game_sessions.id = ranked_sessions.id
    and ranked_sessions.session_rank > 50;

  return new;
end;
$function$;

create or replace function public.quiz_reviewee_user_id()
  returns uuid
  language plpgsql
  stable
  security definer
  set search_path to ''
  AS $function$
declare
  authenticated_user_id uuid;
begin
  authenticated_user_id := auth.uid();

  if authenticated_user_id is null then
    raise exception 'You must be logged in to play a quiz'
      using errcode = '42501';
  end if;

  if not public.is_current_user_active() then
    raise exception 'Your account has been deactivated'
      using errcode = '42501';
  end if;

  if not exists (
    select 1
    from public.user_roles
    join public.roles on roles.id = user_roles.role_id
    where user_roles.user_id = authenticated_user_id
      and roles.name = 'reviewee'
  ) then
    raise exception 'You are not authorized to play a quiz'
      using errcode = '42501';
  end if;

  return authenticated_user_id;
end;
