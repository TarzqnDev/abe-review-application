create or replace function public.advance_flash_card_session(
  selected_session_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  authenticated_user_id uuid;
  selected_session public.game_sessions%rowtype;
  current_flash_card public.game_session_flash_cards%rowtype;
  next_flash_card public.game_session_flash_cards%rowtype;
  activated_time timestamptz;
  flash_card_deadline timestamptz;
begin
  authenticated_user_id := public.flash_card_reviewee_user_id();

  select game_sessions.*
  into selected_session
  from public.game_sessions
  where game_sessions.id = selected_session_id
    and game_sessions.user_id = authenticated_user_id
    and game_sessions.session_type = 'flash_cards'
  for update;

  if not found then
    raise exception 'Flash card session was not found'
      using errcode = 'P0002';
  end if;

  if selected_session.status <> 'in_progress' then
    raise exception 'Flash card session cannot be advanced'
      using errcode = '55000';
  end if;

  select game_session_flash_cards.*
  into current_flash_card
  from public.game_session_flash_cards
  where game_session_flash_cards.session_id = selected_session_id
    and game_session_flash_cards.card_order =
      selected_session.current_question_order
  for update;

  if not found then
    raise exception 'The current flash card was not found'
      using errcode = 'P0002';
  end if;

  if current_flash_card.status not in ('answered', 'timed_out') then
    raise exception 'The current flash card is not finished'
      using errcode = '55000';
  end if;

  if selected_session.current_question_order >=
    selected_session.total_questions
  then
    update public.game_sessions
    set
      status = 'completed',
      end_reason = 'completed',
      ended_at = clock_timestamp()
    where id = selected_session_id;

    return jsonb_build_object(
      'completed', true,
      'timing', null,
      'summary', public.flash_card_session_summary(
        selected_session_id,
        authenticated_user_id
      )
    );
  end if;

  select game_session_flash_cards.*
  into next_flash_card
  from public.game_session_flash_cards
  where game_session_flash_cards.session_id = selected_session_id
    and game_session_flash_cards.card_order =
      selected_session.current_question_order + 1
    and game_session_flash_cards.status = 'pending'
  for update;

  if not found then
    raise exception 'The next flash card was not found'
      using errcode = 'P0002';
  end if;

  activated_time := clock_timestamp();
  flash_card_deadline := activated_time
    + make_interval(secs => selected_session.timer_seconds);

  update public.game_session_flash_cards
  set
    status = 'active',
    presented_at = activated_time,
    deadline_at = flash_card_deadline
  where id = next_flash_card.id;

  update public.game_sessions
  set current_question_order = next_flash_card.card_order
  where id = selected_session_id;

  return jsonb_build_object(
    'completed', false,
    'timing', jsonb_build_object(
      'sessionId', selected_session_id,
      'sessionFlashCardId', next_flash_card.id,
      'cardOrder', next_flash_card.card_order,
      'status', 'active',
      'serverNow', activated_time,
      'deadlineAt', flash_card_deadline
    ),
    'summary', null
  );
end;
$$;

