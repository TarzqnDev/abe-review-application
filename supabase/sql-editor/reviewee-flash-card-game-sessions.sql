create or replace function public.flash_card_session_summary(
  selected_session_id uuid,
  authenticated_user_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  selected_session public.game_sessions%rowtype;
  correct_count integer;
  incorrect_count integer;
  timed_out_count integer;
  not_played_count integer;
  questions_reached_count integer;
  answered_count integer;
  completed_question_count integer;
  accuracy_percentage numeric;
  completion_percentage numeric;
  duration_seconds integer;
begin
  select game_sessions.*
  into selected_session
  from public.game_sessions
  where game_sessions.id = selected_session_id
    and game_sessions.user_id = authenticated_user_id
    and game_sessions.session_type = 'flash_cards';

  if not found then
    raise exception 'Flash card session was not found'
      using errcode = 'P0002';
  end if;

  select
    count(*) filter (where result = 'correct'),
    count(*) filter (where result = 'incorrect'),
    count(*) filter (where status = 'timed_out'),
    count(*) filter (where status in ('abandoned', 'not_played')),
    count(*) filter (
      where status in (
        'active',
        'submitted',
        'answered',
        'timed_out',
        'abandoned'
      )
    )
  into
    correct_count,
    incorrect_count,
    timed_out_count,
    not_played_count,
    questions_reached_count
  from public.game_session_flash_cards
  where session_id = selected_session_id;

  answered_count := correct_count + incorrect_count;
  completed_question_count := answered_count + timed_out_count;

  accuracy_percentage := case
    when answered_count = 0 then 0
    else round((correct_count::numeric / answered_count::numeric) * 100, 2)
  end;

  completion_percentage := case
    when selected_session.total_questions = 0 then 0
    else round(
      (
        completed_question_count::numeric
        / selected_session.total_questions::numeric
      ) * 100,
      2
    )
  end;

  duration_seconds := case
    when selected_session.started_at is null then 0
    else greatest(
      0,
      floor(
        extract(
          epoch from (
            coalesce(selected_session.ended_at, clock_timestamp())
            - selected_session.started_at
          )
        )
      )::integer
    )
  end;

  return jsonb_build_object(
    'sessionId', selected_session.id,
    'status', selected_session.status,
    'endReason', selected_session.end_reason,
    'areaId', selected_session.area_id,
    'areaName', selected_session.area_name,
    'gameType', selected_session.game_type,
    'difficulty', selected_session.difficulty,
    'totalQuestions', selected_session.total_questions,
    'correct', correct_count,
    'incorrect', incorrect_count,
    'timedOut', timed_out_count,
    'notPlayed', not_played_count,
    'questionsReached', questions_reached_count,
    'answered', answered_count,
    'accuracyPercentage', accuracy_percentage,
    'completionPercentage', completion_percentage,
    'durationSeconds', duration_seconds
  );
end;
$$;

create or replace function public.prepare_flash_card_session(
  selected_area_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  authenticated_user_id uuid;
  selected_deck public.flash_card_decks%rowtype;
  selected_area_name text;
  created_session_id uuid;
  created_session_flash_card_id bigint;
  flash_card_number integer := 0;
  selected_flash_card record;
  prepared_flash_cards jsonb;
  selected_timer_seconds constant smallint := 10;
begin
  authenticated_user_id := public.flash_card_reviewee_user_id();

  select flash_card_decks.*
  into selected_deck
  from public.flash_card_decks
  where flash_card_decks.user_id = authenticated_user_id
    and flash_card_decks.area_id = selected_area_id;

  if not found then
    return jsonb_build_object('status', 'empty');
  end if;

  select subject_areas.name
  into selected_area_name
  from public.subject_areas
  where subject_areas.id = selected_area_id;

  if not found then
    raise exception 'A valid subject area is required'
      using errcode = '22023';
  end if;

  insert into public.game_sessions (
    user_id,
    area_id,
    area_name,
    session_type,
    flash_card_deck_id,
    game_type,
    difficulty,
    timer_seconds
  )
  values (
    authenticated_user_id,
    selected_area_id,
    selected_area_name,
    'flash_cards',
    selected_deck.id,
    'Flash Cards',
    null,
    selected_timer_seconds
  )
  returning id into created_session_id;

  for selected_flash_card in
    select
      flash_cards.id,
      flash_cards.question,
      flash_cards.answer
    from public.flash_cards
    where flash_cards.deck_id = selected_deck.id
    order by random()
  loop
    flash_card_number := flash_card_number + 1;

    insert into public.game_session_flash_cards (
      session_id,
      flash_card_id,
      question_text,
      card_order
    )
    values (
      created_session_id,
      selected_flash_card.id,
      selected_flash_card.question,
      flash_card_number
    )
    returning id into created_session_flash_card_id;

    insert into public.game_session_flash_card_answer_keys (
      session_flash_card_id,
      correct_answer
    )
    values (
      created_session_flash_card_id,
      selected_flash_card.answer
    );
  end loop;

  if flash_card_number = 0 then
    delete from public.game_sessions
    where id = created_session_id;

    return jsonb_build_object('status', 'empty');
  end if;

  update public.game_sessions
  set total_questions = flash_card_number
  where id = created_session_id;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'sessionFlashCardId', game_session_flash_cards.id,
        'cardOrder', game_session_flash_cards.card_order,
        'questionText', game_session_flash_cards.question_text
      )
      order by game_session_flash_cards.card_order
    ),
    '[]'::jsonb
  )
  into prepared_flash_cards
  from public.game_session_flash_cards
  where game_session_flash_cards.session_id = created_session_id;

  return jsonb_build_object(
    'status', 'prepared',
    'sessionId', created_session_id,
    'areaId', selected_area_id,
    'areaName', selected_area_name,
    'timerSeconds', selected_timer_seconds,
    'totalFlashCards', flash_card_number,
    'flashCards', prepared_flash_cards
  );
end;
$$;

create or replace function public.start_flash_card_session(
  selected_session_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  authenticated_user_id uuid;
  selected_session public.game_sessions%rowtype;
  first_flash_card public.game_session_flash_cards%rowtype;
  started_time timestamptz;
  flash_card_deadline timestamptz;
begin
  authenticated_user_id := public.flash_card_reviewee_user_id();

  select game_sessions.*
  into selected_session
  from public.game_sessions
  where game_sessions.id = selected_session_id
    and game_sessions.user_id = authenticated_user_id
    and game_sessions.session_type = 'flash_cards'
  for update;

  if not found then
    raise exception 'Flash card session was not found'
      using errcode = 'P0002';
  end if;

  if selected_session.status <> 'ready' then
    raise exception 'Flash card session cannot be started'
      using errcode = '55000';
  end if;

  select game_session_flash_cards.*
  into first_flash_card
  from public.game_session_flash_cards
  where game_session_flash_cards.session_id = selected_session_id
    and game_session_flash_cards.card_order = 1
  for update;

  if not found then
    raise exception 'Flash card session does not contain cards'
      using errcode = '55000';
  end if;

  started_time := clock_timestamp();
  flash_card_deadline := started_time
    + make_interval(secs => selected_session.timer_seconds);

  update public.game_sessions
  set
    status = 'in_progress',
    current_question_order = 1,
    started_at = started_time
  where id = selected_session_id;

  update public.game_session_flash_cards
  set
    status = 'active',
    presented_at = started_time,
    deadline_at = flash_card_deadline
  where id = first_flash_card.id;

  return jsonb_build_object(
    'sessionId', selected_session_id,
    'sessionFlashCardId', first_flash_card.id,
    'cardOrder', 1,
    'status', 'active',
    'serverNow', started_time,
    'deadlineAt', flash_card_deadline
  );
end;
$$;

create or replace function public.submit_flash_card_answer(
  selected_session_flash_card_id bigint,
  selected_answer text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  authenticated_user_id uuid;
  selected_session public.game_sessions%rowtype;
  selected_flash_card public.game_session_flash_cards%rowtype;
  submitted_time timestamptz;
  answer_reveal_time timestamptz;
begin
  authenticated_user_id := public.flash_card_reviewee_user_id();

  if selected_answer is null
    or char_length(btrim(selected_answer)) not between 1 and 2000
  then
    raise exception 'A valid answer is required'
      using errcode = '22023';
  end if;

  select game_sessions.*
  into selected_session
  from public.game_sessions
  join public.game_session_flash_cards
    on game_session_flash_cards.session_id = game_sessions.id
  where game_session_flash_cards.id = selected_session_flash_card_id
    and game_sessions.user_id = authenticated_user_id
    and game_sessions.session_type = 'flash_cards'
  for update of game_sessions;

  if not found then
    raise exception 'Flash card was not found'
      using errcode = 'P0002';
  end if;

  select game_session_flash_cards.*
  into selected_flash_card
  from public.game_session_flash_cards
  where game_session_flash_cards.id = selected_session_flash_card_id
  for update;

  if selected_session.status <> 'in_progress'
    or selected_session.current_question_order <> selected_flash_card.card_order
    or selected_flash_card.status <> 'active'
  then
    raise exception 'Flash card is not accepting answers'
      using errcode = '55000';
  end if;

  submitted_time := clock_timestamp();

  if selected_flash_card.deadline_at is null
    or submitted_time > selected_flash_card.deadline_at
  then
    raise exception 'The answer deadline has passed'
      using errcode = '57014';
  end if;

  answer_reveal_time := submitted_time + interval '3 seconds';

  update public.game_session_flash_cards
  set
    status = 'submitted',
    submitted_answer = btrim(selected_answer),
    submitted_at = submitted_time,
    reveal_at = answer_reveal_time,
    response_time_ms = greatest(
      0,
      floor(
        extract(epoch from (submitted_time - selected_flash_card.presented_at))
        * 1000
      )::integer
    )
  where id = selected_session_flash_card_id;

  return jsonb_build_object(
    'sessionFlashCardId', selected_session_flash_card_id,
    'status', 'submitted',
    'submittedAt', submitted_time,
    'revealAt', answer_reveal_time
  );
end;
$$;

create or replace function public.reveal_flash_card_answer(
  selected_session_flash_card_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  authenticated_user_id uuid;
  selected_flash_card public.game_session_flash_cards%rowtype;
  correct_answer text;
  answer_is_correct boolean;
  answer_result text;
  resolved_time timestamptz;
begin
  authenticated_user_id := public.flash_card_reviewee_user_id();

  select game_session_flash_cards.*
  into selected_flash_card
  from public.game_session_flash_cards
  join public.game_sessions
    on game_sessions.id = game_session_flash_cards.session_id
  where game_session_flash_cards.id = selected_session_flash_card_id
    and game_sessions.user_id = authenticated_user_id
    and game_sessions.session_type = 'flash_cards'
    and game_sessions.status = 'in_progress'
  for update of game_session_flash_cards;

  if not found then
    raise exception 'Flash card was not found'
      using errcode = 'P0002';
  end if;

  if selected_flash_card.status <> 'submitted'
    or selected_flash_card.submitted_answer is null
    or selected_flash_card.reveal_at is null
  then
    raise exception 'Flash card answer is not ready to be revealed'
      using errcode = '55000';
  end if;

  resolved_time := clock_timestamp();

  if resolved_time < selected_flash_card.reveal_at then
    raise exception 'Flash card answer cannot be revealed yet'
      using errcode = '55000';
  end if;

  select game_session_flash_card_answer_keys.correct_answer
  into correct_answer
  from public.game_session_flash_card_answer_keys
  where game_session_flash_card_answer_keys.session_flash_card_id =
    selected_session_flash_card_id;

  if not found then
    raise exception 'Flash card answer key was not found'
      using errcode = 'P0002';
  end if;

  answer_is_correct := public.normalize_flash_card_answer(
    selected_flash_card.submitted_answer
  ) = public.normalize_flash_card_answer(correct_answer);
  answer_result := case
    when answer_is_correct then 'correct'
    else 'incorrect'
  end;

  update public.game_session_flash_cards
  set
    status = 'answered',
    result = answer_result,
    resolved_at = resolved_time
  where id = selected_session_flash_card_id;

  return jsonb_build_object(
    'sessionFlashCardId', selected_session_flash_card_id,
    'status', 'answered',
    'result', answer_result,
    'isCorrect', answer_is_correct,
    'correctAnswer', correct_answer,
    'resolvedAt', resolved_time
  );
end;
$$;

create or replace function public.timeout_flash_card(
  selected_session_flash_card_id bigint
